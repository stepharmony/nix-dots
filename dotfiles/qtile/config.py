# nix-dots: HiDPI. X11 has no compositor scaling, so each toolkit is told
# separately. The scale is guessed from the first output's DPI like niri
# does (spectre's 3K panel → 1.75, a normal monitor → 1), rounded to a
# quarter; QTILE_SCALE overrides it.
def _guess_scale():
    if "QTILE_SCALE" in os.environ:
        return float(os.environ["QTILE_SCALE"])
    try:
        query = subprocess.run(["xrandr", "--query"], capture_output=True, text=True).stdout
    except OSError:
        return 1.0
    for m in re.finditer(r" connected (?:primary )?(\d+)x\d+\+\d+\+\d+ .*?(\d+)mm x \d+mm", query):
        width, mm = int(m[1]), int(m[2])
        if mm:
            return min(3.0, max(1.0, round(width / (mm / 25.4) / 144 * 4) / 4))
    return 1.0


scale = _guess_scale()


